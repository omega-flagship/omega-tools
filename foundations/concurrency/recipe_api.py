"""Three fixed job-local recipes; no caller expression, namespace or executor.

PeTTa supplies hyperpose/with_mutex/transaction. This is a typed recipe layer,
not an invention or replacement of those engine primitives.
"""
import json
import re
import uuid

SCHEMA = 'omega-tools-concurrency-request/v1'
RECIPES = {'parallel-map', 'mutex-counter', 'transaction-counter'}
IDENT = re.compile(r'[a-z][a-z0-9_-]{0,47}\Z')


def keys(value, names):
    if type(value) is not dict or len(value) != len(names) or set(value) != set(names):
        raise ValueError('closed-object-required')


def integer(value, bound):
    if type(value) is not int or not -bound <= value <= bound:
        raise ValueError('bounded-integer-required')


def validate(request):
    keys(request, ('schema', 'recipe', 'input'))
    if request['schema'] != SCHEMA or type(request['recipe']) is not str or request['recipe'] not in RECIPES:
        raise ValueError('unknown-recipe-or-schema')
    x = request['input']
    if request['recipe'] == 'parallel-map':
        keys(x, ('tasks',))
        if type(x['tasks']) is not list or not 1 <= len(x['tasks']) <= 8:
            raise ValueError('task-count-limit')
        seen = set()
        for task in x['tasks']:
            keys(task, ('id', 'value', 'increment'))
            if type(task['id']) is not str or len(task['id']) > 48 or not IDENT.fullmatch(task['id']) or task['id'] in seen:
                raise ValueError('unique-literal-task-id-required')
            seen.add(task['id'])
            integer(task['value'], 10000); integer(task['increment'], 100)
    elif request['recipe'] == 'mutex-counter':
        keys(x, ('initial', 'increments')); integer(x['initial'], 10000)
        if type(x['increments']) is not list or not 1 <= len(x['increments']) <= 8:
            raise ValueError('task-count-limit')
        for delta in x['increments']: integer(delta, 100)
    else:
        keys(x, ('initial', 'delta', 'commit'))
        integer(x['initial'], 10000); integer(x['delta'], 100)
        if type(x['commit']) is not bool: raise ValueError('boolean-commit-required')
    return request


def compile_recipe(request, *, namespace=None):
    # Reviewer/worker parameter only, never a request field. Fresh for every job.
    namespace = 'wave_job_' + uuid.uuid4().hex if namespace is None else namespace
    if type(namespace) is not str or not re.fullmatch(r'wave_job_[0-9a-f]{32}', namespace):
        raise ValueError('invalid-worker-namespace')
    space = '&' + namespace
    mutex = 'wave_lock_' + namespace.removeprefix('wave_job_')
    validate(request); x = request['input']; recipe = request['recipe']
    if recipe == 'parallel-map':
        branches = ' '.join('(let $value (+ ' + str(t['value']) + ' ' + str(t['increment']) + ') (WaveBranch ' + json.dumps(t['id']) + ' $value))' for t in x['tasks'])
        return '!(WaveResult (collapse (hyperpose (' + branches + '))))\n'
    # Names are generated by the worker; process isolation remains independent.
    source = '!(add-atom ' + space + ' (WaveCount ' + str(x['initial']) + '))\n'
    update = '(match ' + space + ' (WaveCount $x) (progn (remove-atom ' + space + ' (WaveCount $x)) (let $next (+ $x $delta) (add-atom ' + space + ' (WaveCount $next)))))'
    if recipe == 'mutex-counter':
        source += '(= (WaveIncrement $id $delta) (with_mutex ' + mutex + ' (progn ' + update + ' (WaveDone $id))))\n'
        branches = ' '.join('(WaveIncrement ' + str(i) + ' ' + str(d) + ')' for i, d in enumerate(x['increments']))
        source += '!(collapse (hyperpose (' + branches + ')))\n'
    else:
        body = '(progn ' + update.replace('$delta', str(x['delta'])) + ' ' + ('True' if x['commit'] else '(empty)') + ')'
        source += '!(transaction ' + body + ')\n'
    return source + '!(WaveResult (match ' + space + ' (WaveCount $x) (WaveCount $x)))\n'


def expected(request):
    validate(request); x = request['input']; recipe = request['recipe']
    if recipe == 'parallel-map':
        return {'recipe': recipe, 'rows': [{'id': t['id'], 'value': t['value'] + t['increment']} for t in x['tasks']]}
    value = x['initial'] + (sum(x['increments']) if recipe == 'mutex-counter' else x['delta'] if x['commit'] else 0)
    return {'recipe': recipe, 'initial': x['initial'], 'value': value,
            **({'committed': x['commit']} if recipe == 'transaction-counter' else {})}


def decode_result(request, text):
    validate(request)
    if type(text) is not str or len(text) > 4096: raise ValueError('result-byte-limit')
    if request['recipe'] == 'parallel-map':
        root = re.fullmatch(r'\(WaveResult\s+\((.*)\)\)', text, re.S)
        if not root: raise ValueError('invalid-result-root')
        body = root[1]
        pattern = r'\(WaveBranch\s+"([a-z][a-z0-9_-]{0,47})"\s+(-?[0-9]{1,5})\)'
        rows = re.findall(pattern, body)
        if re.sub(pattern, '', body).strip() or len(rows) != len(request['input']['tasks']):
            raise ValueError('partial-or-invalid-result')
        by_id = dict(rows)
        ids = [t['id'] for t in request['input']['tasks']]
        if len(by_id) != len(rows) or set(by_id) != set(ids): raise ValueError('duplicate-or-unknown-result')
        result = {'recipe': request['recipe'], 'rows': [{'id': i, 'value': int(by_id[i])} for i in ids]}
    else:
        match = re.fullmatch(r'\(WaveResult\s+\(WaveCount\s+(-?[0-9]{1,5})\)\)', text)
        if not match: raise ValueError('invalid-counter-result')
        result = expected(request); result['value'] = int(match[1])
    # Detect missing work/lost updates; never synthesize a native success.
    if result != expected(request): raise ValueError('native-result-mismatch')
    return result
